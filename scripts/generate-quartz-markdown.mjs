#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import process from "node:process"

const SONG_TAGS = ["song", "spotify"]
const ARTIST_TAGS = ["artist"]
const GENRE_TAGS = ["genre"]
const REQUIRED_FIELDS = ["trackName", "artistName", "genre", "spotifyUrl"]

async function main() {
  const repoRoot = path.resolve(new URL("..", import.meta.url).pathname)
  const input = await loadInput(process.argv[2])
  const songs = normalizeSongs(input)

  await Promise.all([
    mkdir(path.join(repoRoot, "content", "songs"), { recursive: true }),
    mkdir(path.join(repoRoot, "content", "artists"), { recursive: true }),
    mkdir(path.join(repoRoot, "content", "genres"), { recursive: true }),
  ])

  for (const song of songs) {
    validateSong(song)

    const songTitle = song.trackName.trim()
    const artistName = song.artistName.trim()
    const genreName = song.genre.trim()

    await writeMarkdownFile(
      path.join(repoRoot, "content", "songs", `${sanitizeFileName(songTitle)}.md`),
      buildSongMarkdown(song),
    )

    await ensurePlaceholder(
      path.join(repoRoot, "content", "artists", `${sanitizeFileName(artistName)}.md`),
      buildPlaceholderMarkdown(artistName, ARTIST_TAGS, "Autogenerated placeholder for artist notes."),
    )

    await ensurePlaceholder(
      path.join(repoRoot, "content", "genres", `${sanitizeFileName(genreName)}.md`),
      buildPlaceholderMarkdown(genreName, GENRE_TAGS, "Autogenerated placeholder for genre notes."),
    )
  }

  console.log(`Processed ${songs.length} song file(s).`)
}

async function loadInput(inputArg) {
  if (inputArg) {
    const inputPath = path.resolve(process.cwd(), inputArg)
    const raw = await readFile(inputPath, "utf8")
    return JSON.parse(raw)
  }

  if (process.stdin.isTTY) {
    throw new Error("Provide a JSON file path or pipe JSON into stdin.")
  }

  let raw = ""
  for await (const chunk of process.stdin) {
    raw += chunk
  }

  return JSON.parse(raw)
}

function normalizeSongs(input) {
  if (Array.isArray(input)) {
    return input
  }

  if (Array.isArray(input?.songs)) {
    return input.songs
  }

  throw new Error("Input must be an array of songs or an object with a songs array.")
}

function validateSong(song) {
  if (!song || typeof song !== "object") {
    throw new Error("Each song entry must be an object.")
  }

  for (const field of REQUIRED_FIELDS) {
    if (typeof song[field] !== "string" || song[field].trim().length === 0) {
      throw new Error(`Song is missing required field: ${field}`)
    }
  }

  if (song.lyrics != null && typeof song.lyrics !== "string") {
    throw new Error("lyrics must be a string when provided.")
  }
}

function buildSongMarkdown(song) {
  const title = song.trackName.trim()
  const artist = song.artistName.trim()
  const genre = song.genre.trim()
  const frontmatter = renderFrontmatter({
    title,
    tags: SONG_TAGS,
    artist: wikiLink(artist),
    genre: wikiLink(genre),
    spotify: song.spotifyUrl.trim(),
  })

  const sections = [
    frontmatter,
    `# ${escapeInlineText(title)}`,
    "",
    `- Artist: ${wikiLink(artist)}`,
    `- Genre: ${wikiLink(genre)}`,
    `- Spotify: ${song.spotifyUrl.trim()}`,
  ]

  if (song.lyrics?.trim()) {
    sections.push("", "## Lyrics", "", song.lyrics.trim())
  }

  return `${sections.join("\n")}\n`
}

function buildPlaceholderMarkdown(title, tags, body) {
  return `${renderFrontmatter({ title, tags })}${body}\n`
}

function renderFrontmatter(fields) {
  const lines = ["---"]

  for (const [key, value] of Object.entries(fields)) {
    if (Array.isArray(value)) {
      lines.push(`${key}:`)
      for (const item of value) {
        lines.push(`  - ${quoteYamlString(item)}`)
      }
      continue
    }

    lines.push(`${key}: ${quoteYamlString(value)}`)
  }

  lines.push("---", "")
  return `${lines.join("\n")}\n`
}

function quoteYamlString(value) {
  return JSON.stringify(String(value))
}

function wikiLink(value) {
  return `[[${value.trim()}]]`
}

function sanitizeFileName(value) {
  return value
    .normalize("NFKC")
    .replace(/[<>:"/\\|?*\u0000-\u001F]/g, "-")
    .replace(/\s+/g, " ")
    .replace(/\.+$/g, "")
    .trim()
}

function escapeInlineText(value) {
  return value.replace(/\r?\n/g, " ").trim()
}

async function writeMarkdownFile(filePath, content) {
  await writeFile(filePath, content, "utf8")
}

async function ensurePlaceholder(filePath, content) {
  try {
    await readFile(filePath, "utf8")
  } catch (error) {
    if (error?.code === "ENOENT") {
      await writeMarkdownFile(filePath, content)
      return
    }

    throw error
  }
}

main().catch((error) => {
  console.error(error.message)
  process.exitCode = 1
})
